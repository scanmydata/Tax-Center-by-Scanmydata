package gr.scanmydata.taxcenter.engine

/**
 * Τι **συνέβη** σε μια εκτέλεση, σε λόγια που καταλαβαίνει ο λογιστής.
 *
 * Ο engine επιστρέφει αναγνωριστικά γραμμένα για προγραμματιστή — `LandPage`,
 * `ViewState`, `NoDeclarationsRow`. Στην οθόνη αυτά έβγαιναν αυτούσια, και μαζί
 * με το «0 έντυπα» άφηναν αναπάντητη τη μόνη ερώτηση που έχει ο χρήστης:
 *
 *  * **βρέθηκε** έντυπο;
 *  * η πύλη απάντησε και **δεν υπάρχει** έντυπο;
 *  * **δεν έγινε σύνδεση** — άρα δεν ξέρουμε αν υπάρχει;
 *  * ή **κάτι χάλασε** στη μέση;
 *
 * Οι τέσσερις απαντήσεις θέλουν διαφορετική ενέργεια: τίποτα, έλεγχο έτους,
 * έλεγχο κωδικών, επανάληψη. Γι' αυτό κάθε λόγος παίρνει εδώ **κατηγορία**,
 * και η οθόνη μιλά με την κατηγορία πρώτα και τη λεπτομέρεια μετά.
 *
 * Καθαρή Kotlin: κάθε μήνυμα που βλέπει ο χρήστης ελέγχεται με τεστ.
 */
object FetchOutcome {

    enum class Kind(val title: String) {
        /** Οι κωδικοί απορρίφθηκαν, ή ο λογαριασμός δεν μπαίνει στην υπηρεσία. */
        LOGIN("Δεν έγινε σύνδεση"),

        /** Λείπει κάτι από την καρτέλα — δεν έγινε καν προσπάθεια. */
        MISSING("Λείπουν στοιχεία στην καρτέλα"),

        /** Η πύλη απάντησε κανονικά: αυτό που ζητήθηκε δεν υπάρχει. */
        NOT_FOUND("Δεν βρέθηκε"),

        /** Δεν φτάσαμε στην πύλη, ή δεν απάντησε εγκαίρως. */
        NETWORK("Πρόβλημα σύνδεσης στο δίκτυο"),

        /** Η πύλη απάντησε με κάτι που δεν περιμέναμε. */
        PORTAL("Η πύλη δεν απάντησε όπως αναμενόταν"),
    }

    data class Explained(val kind: Kind, val text: String) {
        /**
         * Αξίζει να ξαναδοκιμαστεί όπως είναι;
         *
         * **Όχι** όταν απορρίφθηκαν οι κωδικοί: το GSIS κλειδώνει τον λογαριασμό
         * μετά από επανειλημμένες αποτυχίες, και ένα κουμπί «επανάληψη» που
         * ξαναστέλνει τους ίδιους λάθος κωδικούς είναι ο συντομότερος δρόμος
         * προς το κλείδωμα. Ούτε όταν λείπουν στοιχεία ή το ζητούμενο δεν
         * υπάρχει — το αποτέλεσμα θα ήταν το ίδιο.
         */
        val retryable: Boolean get() = kind == Kind.NETWORK || kind == Kind.PORTAL
    }

    /** Η εξήγηση ενός λόγου αποτυχίας, όπως τον έδωσε ο engine. */
    fun explain(reason: String): Explained {
        val raw = reason.trim()
        KNOWN[raw]?.let { return it }

        // Οι λόγοι με πρόθεμα κουβαλούν από πίσω μήνυμα εξαίρεσης ή κωδικό HTTP.
        PREFIXED.entries.firstOrNull { raw.startsWith(it.key) }?.let { return it.value }

        val lower = raw.lowercase()
        return when {
            raw.isBlank() -> Explained(Kind.PORTAL, "Η διαδικασία σταμάτησε χωρίς να πει γιατί. Δοκίμασε ξανά.")

            // Ο `ProcessRunner` γράφει ήδη ελληνικά, με το ΑΦΜ του πελάτη.
            raw.startsWith("Λείπουν") || raw.startsWith("Λείπει") -> Explained(Kind.MISSING, raw)

            lower.contains("oam-6") || lower.contains("μέγιστος αριθμός περιόδων") -> Explained(
                Kind.LOGIN,
                "Το GSIS αρνήθηκε τη σύνδεση: ο λογαριασμός έχει ήδη ανοιχτές συνεδρίες. " +
                    "Περίμενε μερικά λεπτά πριν ξαναδοκιμάσεις.",
            )

            raw.startsWith("Λήξη χρόνου") -> Explained(
                Kind.NETWORK,
                "Η πύλη άργησε πολύ να απαντήσει και η διαδικασία διακόπηκε. Δοκίμασε ξανά — " +
                    "αν επιμένει, η υπηρεσία μάλλον είναι φορτωμένη αυτή την ώρα.",
            )

            NETWORK_HINTS.any { lower.contains(it) } -> Explained(
                Kind.NETWORK,
                "Δεν υπήρξε σύνδεση με την πύλη. Έλεγξε το δίκτυο της συσκευής και δοκίμασε ξανά.",
            )

            else -> Explained(
                Kind.PORTAL,
                "Η διαδικασία σταμάτησε απρόσμενα ($raw). Δοκίμασε ξανά· αν επιμένει, η πύλη " +
                    "μάλλον άλλαξε και χρειάζεται νέα έκδοση της εφαρμογής.",
            )
        }
    }

    /**
