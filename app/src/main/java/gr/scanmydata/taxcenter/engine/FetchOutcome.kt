     *
     * Δεν είναι παντού το ίδιο. Στο Ε1 σημαίνει «δεν έχει υποβληθεί δήλωση για
     * αυτό το έτος»· στις οφειλές σημαίνει «δεν χρωστάει» — που είναι καλό νέο,
     * όχι κενό αποτέλεσμα. Ένα κοινό «δεν βρέθηκε έντυπο» έκανε και τα δύο να
     * μοιάζουν με αστοχία.
     */
