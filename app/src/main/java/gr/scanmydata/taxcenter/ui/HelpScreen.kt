@Composable
fun HelpScreen(container: AppContainer, modifier: Modifier = Modifier) {
    LazyColumn(modifier.padding(horizontal = 16.dp)) {
        item {
            Spacer(Modifier.height(12.dp))
            Card(
                colors = CardDefaults.cardColors(
                    containerColor = MaterialTheme.colorScheme.secondaryContainer,
                ),
                modifier = Modifier.fillMaxWidth(),
            ) {
                Column(Modifier.padding(14.dp)) {
                    Text("ScanMyData Tax Center", style = MaterialTheme.typography.titleMedium)
                    Text(
                        "έκδοση ${BuildConfig.VERSION_NAME}",
                        style = MaterialTheme.typography.labelSmall,
                    )
                    Spacer(Modifier.height(8.dp))
                    Text(
                        "Η εφαρμογή κατεβάζει τα φορολογικά και ασφαλιστικά έντυπα των " +
                            "πελατών σου εκτελώντας τις ίδιες διαδικασίες που θα έκανες με " +
                            "το χέρι στις πύλες, και τα στέλνει με το Gmail σου. Όλα " +
                            "γίνονται **στη συσκευή**: δεν υπάρχει διακομιστής μας, και " +
                            "κανένα δεδομένο πελάτη δεν φεύγει προς εμάς.",
                        style = MaterialTheme.typography.bodySmall,
                    )
                    Spacer(Modifier.height(10.dp))
                    OutlinedButton(onClick = { TourState.start() }) { Text("Ξανά η ξενάγηση") }
                }
            }
            Spacer(Modifier.height(12.dp))
        }

        items(SECTIONS, key = { it.title }) { section -> HelpSection(section) }

        item { Spacer(Modifier.height(24.dp)) }
    }

}

private data class Section(val title: String, val body: List<Pair<String, String>>)

@Composable
private fun HelpSection(section: Section) {
    var open by remember { mutableStateOf(false) }
    Card(
        Modifier.fillMaxWidth().padding(vertical = 4.dp).clickable { open = !open },
    ) {
        Column(Modifier.padding(14.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(
                    section.title,
                    style = MaterialTheme.typography.titleSmall,
                    modifier = Modifier.weight(1f),
                )
                Text(if (open) "−" else "+", style = MaterialTheme.typography.titleMedium)
            }
            AnimatedVisibility(open) {
                Column {
                    Spacer(Modifier.height(8.dp))
                    section.body.forEachIndexed { index, (heading, text) ->
                        if (index > 0) {
                            Spacer(Modifier.height(10.dp))
                            HorizontalDivider()
                            Spacer(Modifier.height(10.dp))
                        }
                        if (heading.isNotBlank()) {
                            Text(heading, style = MaterialTheme.typography.labelLarge)
                            Spacer(Modifier.height(2.dp))
                        }
                        Text(text, style = MaterialTheme.typography.bodySmall)
                    }
                }
            }
        }
    }
}

