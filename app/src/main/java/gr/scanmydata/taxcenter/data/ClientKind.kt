package gr.scanmydata.taxcenter.data

/**
 * Το είδος του υπόχρεου — τρεις τιμές, όχι ελεύθερο κείμενο.
 *
 * Δεν είναι ετικέτα για την οθόνη· καθορίζει τι ισχύει:
 *
 *  * **ΑΜΚΑ έχουν μόνο ο ιδιώτης και η ατομική επιχείρηση.** Πίσω τους υπάρχει
 *    φυσικό πρόσωπο. Σε νομικό πρόσωπο το πεδίο δεν είναι κενό — δεν υφίσταται,
 *    και η καρτέλα ούτε το δείχνει ούτε το ζητά.
 *  * Οι διαδικασίες ΕΦΚΑ/ΑΤΛΑΣ/ΚΕΑΟ θέλουν ΑΜΚΑ στη φόρμα ρόλου, άρα δεν έχουν
 *    νόημα για νομικό πρόσωπο.
 *
 * **«Ιδιώτης» και όχι «φυσικό πρόσωπο»:** στη γλώσσα του μητρώου, ατομική
 * επιχείρηση *είναι* φυσικό πρόσωπο. Ο όρος θα ίσχυε και για τις δύο πρώτες
 * κατηγορίες και δεν θα ξεχώριζε τίποτα. «Ιδιώτης» λέει αυτό που εννοούμε:
 * φυσικό πρόσωπο **χωρίς** επιχειρηματική δραστηριότητα.
 *
 * Οι τιμές γράφονται κεφαλαία επειδή έτσι έρχονται και από το Μητρώο ΑΑΔΕ
 * (`aade-profile`) — ένα σχήμα, όχι δύο.
 */
object ClientKind {

    const val PRIVATE = "ΙΔΙΩΤΗΣ"
    const val SOLE = "ΑΤΟΜΙΚΗ ΕΠΙΧΕΙΡΗΣΗ"
    const val LEGAL = "ΝΟΜΙΚΟ ΠΡΟΣΩΠΟ"

    val ALL = listOf(PRIVATE, SOLE, LEGAL)

    /** Έχει ΑΜΚΑ; Μόνο όπου υπάρχει φυσικό πρόσωπο από πίσω. */
    fun hasAmka(kind: String): Boolean = normalise(kind) != LEGAL

    /**
     * Δέχεται ό,τι γράφει η στήλη «ΕΙΔΟΣ» των λογιστικών προγραμμάτων και το
     * φέρνει στις τρεις τιμές μας.
     *
     * Η ανοχή είναι σκόπιμη: τα exports γράφουν «Φυσικό Πρόσωπο», «ΦΠ», «Ο.Ε.»,
     * «ΑΤΟΜΙΚΗ». Άγνωστο κείμενο **επιστρέφεται αυτούσιο** αντί να πεταχτεί —
     * μια λάθος κατηγοριοποίηση θα έκρυβε το πεδίο ΑΜΚΑ από κάποιον που το έχει.
     */
    fun normalise(raw: String): String {
        val value = raw.trim()
        if (value.isBlank()) return ""
        if (value in ALL) return value

        val folded = Normalize.header(value)
        return when {
            folded.contains("ατομικ") -> SOLE
            folded.contains("ιδιωτ") -> PRIVATE
            folded.contains("νομικ") -> LEGAL
            // «Φυσικό πρόσωπο» χωρίς άλλη ένδειξη: ιδιώτης. Αν έχει και
            // επιχείρηση, θα το διορθώσει η άντληση από το Μητρώο.
            folded.contains("φυσικ") -> PRIVATE
            else -> value
        }
    }
}
